/* MLP policy evaluated in plain C. Weights come from policy_weights.h,
   generated by tools/export_policy.py. */
#pragma once

#define POLICY_ACTIVATION_NONE  0
#define POLICY_ACTIVATION_TANH  1
#define POLICY_ACTIVATION_RELU  2
#define POLICY_ACTIVATION_ELU   3

/* Network dimensions, exposed so callers can size their buffers */
int policy_obs_dim(void);
int policy_act_dim(void);
int policy_is_placeholder(void);

/* Deterministic forward pass: normalise obs, run the layers, clamp the
   output to [-1, 1]. obs has policy_obs_dim() entries, act policy_act_dim().
   Not reentrant (uses static layer buffers); call from one task only. */
void policy_forward(const float *obs, float *act);

/* Run the reference vectors baked into policy_weights.h and log the largest
   deviation, then time the forward pass. Returns the max abs error. */
float policy_selftest(void);
